// Writes THIRD_PARTY_NOTICES.md: the licenses of everything the built extension contains that is not this package's own.
//
//   node scripts/notices.mjs [--check]
//
// The extension's binaries are Bun's checker and compiler (vendor/bun, `pnpm vendor` first) and the Rust crates Cargo.lock resolves, and the
// package ships TypeScript's lib files (libs/typescript_libs.bin). Each crate's own license files are copied in from Cargo's source of it, so the
// notices carry their copyright lines. `--check` fails when the committed file is not what this would write (CI runs it).
import { spawnSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { parseArguments, root, rustToolchain, withToolchainPath } from './godot-api.mjs';

const args = parseArguments(process.argv.slice(2), { flags: ['--check'], values: [] });
const OUTPUT = join(root, 'THIRD_PARTY_NOTICES.md');
const BUN = join(root, 'vendor/bun');
if (!existsSync(join(BUN, 'provenance.json'))) throw new Error('vendor/bun is missing: run "pnpm vendor" first');
const provenance = JSON.parse(readFileSync(join(BUN, 'provenance.json'), 'utf8'));
const LICENSE_FILE = /^(LICENSE|LICENCE|COPYING|NOTICE|UNLICENSE)([-._].*)?$/iu;

const toolchain = rustToolchain();
const metadata = spawnSync(toolchain.cargo, ['metadata', '--format-version', '1', '--locked'], {
  cwd: root, encoding: 'utf8', maxBuffer: 64 << 20, env: withToolchainPath(toolchain, process.env),
});
if (metadata.error) throw metadata.error;
if (metadata.status !== 0) throw new Error(`cargo metadata failed: ${metadata.stderr}`);
// Crates from a registry or git; the vendored Bun crates (path dependencies) are Bun's, below.
const crates = JSON.parse(metadata.stdout).packages
  .filter(crate => crate.source !== null)
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

function licenseTexts(directory) {
  return readdirSync(directory).filter(name => LICENSE_FILE.test(name)).sort().map(name => ({ name, text: readFileSync(join(directory, name), 'utf8').trim() }));
}

const lines = [
  '# Third-party notices',
  '',
  'godot-tsc is MIT-licensed (LICENSE). Its GDExtension binaries also contain the software below, each under its own license, and the',
  'package ships TypeScript\'s declaration files. This file is generated by `scripts/notices.mjs`; it is shipped in the npm package and in',
  '`addons/godot-tsc/`, so an exported game that includes the extension carries it.',
  '',
  '## Bun',
  '',
  `The type checker (\`bun_sema\`), the JavaScript parser and printer, and the crates they need are Bun's (${provenance.upstream}, revision`,
  `\`${provenance.revision}\`), extracted by \`scripts/vendor-bun.py\` with the patches in \`patches/\`. Bun's repository says "Bun itself is`,
  'MIT-licensed" (its LICENSE.md); none of the libraries that LICENSE.md lists as statically linked into the `bun` executable are part of',
  'this extension (its native stand-ins are plain Rust).',
  '',
  '```',
  'MIT License',
  '',
  'Permission is hereby granted, free of charge, to any person obtaining a copy of this software and associated documentation files',
  '(the "Software"), to deal in the Software without restriction, including without limitation the rights to use, copy, modify, merge,',
  'publish, distribute, sublicense, and/or sell copies of the Software, and to permit persons to whom the Software is furnished to do so,',
  'subject to the following conditions:',
  '',
  'The above copyright notice and this permission notice shall be included in all copies or substantial portions of the Software.',
  '',
  'THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF',
  'MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE',
  'FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION',
  'WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE.',
  '```',
  '',
  '## TypeScript (typescript-go and the lib files)',
  '',
  "Bun's checker is a port of Microsoft's typescript-go (https://github.com/microsoft/typescript-go) and uses TypeScript's diagnostic",
  "messages; `typescript_libs.bin` holds TypeScript's `lib.*.d.ts` files. Both are Apache-2.0, Copyright (c) Microsoft Corporation. The",
  "license and the notice below are typescript-go's, as Bun's repository carries them.",
  '',
  '```',
  readFileSync(join(BUN, 'licenses/typescript-go-LICENSE'), 'utf8').trim(),
  '```',
  '',
  '```',
  readFileSync(join(BUN, 'licenses/typescript-go-NOTICE.txt'), 'utf8').trim(),
  '```',
  '',
  '## Rust crates',
  '',
  'The crates Cargo.lock resolves (some are used only to build). godot-rust (`godot`, `godot-*`, `gdextension-api`) is MPL-2.0: its source',
  'is at https://github.com/godot-rust/gdext, unmodified at the versions listed.',
  '',
  '| Crate | Version | License | Source |',
  '| --- | --- | --- | --- |',
  ...crates.map(crate => `| ${crate.name} | ${crate.version} | ${crate.license ?? crate.license_file ?? 'see below'} | ${crate.repository ?? ''} |`),
  '',
];
for (const crate of crates) {
  const texts = licenseTexts(dirname(crate.manifest_path));
  lines.push(`### ${crate.name} ${crate.version}`, '');
  if (texts.length === 0) {
    // A few crates publish no license file; their manifest's SPDX expression is the license, and its text is below.
    if (!crate.license) throw new Error(`${crate.name} ${crate.version} has neither a license file nor a license in its manifest`);
    lines.push(`Its package has no license file; its manifest declares \`${crate.license}\`. The texts are under "License texts".`, '');
    continue;
  }
  for (const { name, text } of texts) lines.push(`${name}:`, '', '```', text, '```', '');
}
lines.push(
  '## License texts',
  '',
  'For the crates above that carry no license file: MIT is the text under "Bun" (with the crate\'s authors as the copyright holders),',
  'Apache-2.0 the text under "TypeScript", and MPL-2.0 this one (licenses/MPL-2.0.txt):',
  '',
  '```',
  readFileSync(join(root, 'licenses/MPL-2.0.txt'), 'utf8').trim(),
  '```',
);
// Some license files have CRLF line ends; the file is written with LF, as git stores it, so the check agrees on every checkout.
const notices = `${lines.join('\n').replace(/\r\n?/gu, '\n').trimEnd()}\n`;

if (args.flags.has('--check')) {
  const committed = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  if (committed !== notices) {
    console.error('THIRD_PARTY_NOTICES.md is not what scripts/notices.mjs writes: run "pnpm notices" and commit it');
    process.exit(1);
  }
  console.log('THIRD_PARTY_NOTICES.md is current');
} else {
  writeFileSync(OUTPUT, notices);
  console.log(`Wrote ${OUTPUT}: Bun, typescript-go and ${crates.length} crates`);
}
